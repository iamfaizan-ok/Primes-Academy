import React, { useState } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { 
  LucideUserPlus, 
  LucideUser,
  LucideArrowRight, 
  LucideChevronRight, 
  LucideChevronDown,
  LucideSparkles,
  LucideBookOpen,
  LucideArrowLeft,
  LucideCheckCircle2,
  LucideGraduationCap
} from 'lucide-react';
import { studentApi } from '../../../services/api/studentApi';
import Alert from '../../../components/common/Alert';

const STANDARD_COURSES = [
  'IELTS Academic',
  'IELTS General Training',
  'PTE Academic',
  'Spoken English & Fluency',
  'Life Skills A1 / B1',
  'Other'
];

const PRESET_FEES = [40000, 50000, 60000, 75000];

export default function AddStudent() {
  const navigate = useNavigate();

  // Screen State: 'FORM' | 'REVIEW'
  const [isReviewing, setIsReviewing] = useState(false);

  // Form State
  const [name, setName] = useState('');
  const [course, setCourse] = useState('IELTS Academic');
  const [customCourse, setCustomCourse] = useState('');
  const [totalFee, setTotalFee] = useState('60000');
  
  // Auto-generated Unique ID for Review
  const [autoGeneratedId, setAutoGeneratedId] = useState('');

  // Flow State
  const [isGeneratingId, setIsGeneratingId] = useState(false);
  const [isSaving, setIsSaving] = useState(false);
  const [error, setError] = useState('');

  const finalCourse = course === 'Other' ? (customCourse.trim() || 'Custom Course') : course;
  const parsedFeeNumber = parseFloat(totalFee) || 0;

  // Step 1: Click "Save Student" on initial form -> Generate unique ID and open Short Review Form
  const handleProceedToReview = async (e) => {
    e.preventDefault();
    setError('');

    if (!name.trim()) {
      setError('Please enter the student full name.');
      return;
    }

    if (course === 'Other' && !customCourse.trim()) {
      setError('Please specify the custom course name.');
      return;
    }

    if (isNaN(parsedFeeNumber) || parsedFeeNumber < 0) {
      setError('Please enter a valid course fee amount.');
      return;
    }

    try {
      setIsGeneratingId(true);
      // Generate unique 4-digit student ID from database
      const nextId = await studentApi.generateStudentId();
      setAutoGeneratedId(nextId);
      setIsReviewing(true);
    } catch (err) {
      setError(err.message || 'Error generating unique student ID. Please try again.');
    } finally {
      setIsGeneratingId(false);
    }
  };

  // Step 2: Click "Save Student" on Short Review Form -> Save to database and navigate to All Students
  const handleFinalSave = async () => {
    setError('');
    setIsSaving(true);

    try {
      const payload = {
        name: name.trim(),
        course: finalCourse,
        total_fee: parsedFeeNumber,
        student_id: autoGeneratedId
      };

      const created = await studentApi.createStudent(payload);

      // Save complete -> Redirect directly to All Students page with success message
      navigate('/admin/students', {
        state: { 
          message: `Student "${created.name}" (ID: #${created.student_id}) saved successfully to database!` 
        }
      });
    } catch (err) {
      setError(err.message || 'Failed to save student record. Please try again.');
      setIsSaving(false);
    }
  };

  return (
    <div className="space-y-4 max-w-xl mx-auto pb-12">
      {/* Breadcrumb Navigation */}
      <div>
        <div className="flex items-center gap-1.5 text-[11px] font-semibold text-slate-400 uppercase tracking-wider mb-1">
          <Link to="/admin/dashboard" className="hover:text-slate-600 transition-colors">Dashboard</Link>
          <LucideChevronRight className="w-3 h-3 text-slate-300" />
          <Link to="/admin/students" className="hover:text-slate-600 transition-colors">All Students</Link>
          <LucideChevronRight className="w-3 h-3 text-slate-300" />
          <span className="text-blue-600">Add Student</span>
        </div>
        <h1 className="text-xl font-bold text-slate-900 tracking-tight">New Student Admission</h1>
      </div>

      {error && (
        <Alert type="error" message={error} onClose={() => setError('')} />
      )}

      {/* ===================================================================== */}
      {/* SCREEN 1: INITIAL INTAKE FORM                                         */}
      {/* ===================================================================== */}
      {!isReviewing ? (
        <div className="bg-white rounded-2xl border border-slate-200/90 shadow-sm overflow-hidden animate-in fade-in duration-200">
          {/* Card Header */}
          <div className="px-6 py-5 border-b border-slate-100 flex items-center justify-between bg-gradient-to-r from-slate-50/70 via-white to-slate-50/70">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-xl bg-blue-50 border border-blue-100 flex items-center justify-center text-blue-700 shadow-2xs">
                <LucideUserPlus className="w-5 h-5 text-blue-700" />
              </div>
              <div>
                <h2 className="text-sm sm:text-base font-bold text-slate-900 tracking-tight">
                  Student Registration Form
                </h2>
                <p className="text-[11px] text-slate-500 mt-0.5">
                  Fill details to register student and auto-generate unique credentials
                </p>
              </div>
            </div>

            <div className="hidden sm:inline-flex items-center gap-1 px-2.5 py-1 rounded-full bg-slate-100/80 border border-slate-200 text-[10px] font-semibold text-slate-600">
              <LucideSparkles className="w-3 h-3 text-amber-500" />
              <span>Auto 4-Digit ID</span>
            </div>
          </div>

          {/* Form Body */}
          <form onSubmit={handleProceedToReview} className="p-6 space-y-4.5">
            {/* 1. Student Name */}
            <div className="space-y-1.5">
              <label className="block text-xs font-semibold text-slate-700">
                Student Full Name <span className="text-rose-500">*</span>
              </label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                  <LucideUser className="w-4 h-4" />
                </div>
                <input
                  type="text"
                  required
                  autoFocus
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="e.g. Muhammad Ahmad"
                  className="w-full pl-10 pr-3.5 py-2.5 rounded-xl border border-slate-200 bg-white text-slate-900 text-xs sm:text-sm placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-600/15 focus:border-blue-600 transition-all shadow-2xs"
                />
              </div>
            </div>

            {/* 2. Course Selection (Executive Dropdown) */}
            <div className="space-y-1.5">
              <label className="block text-xs font-semibold text-slate-700">
                Enrolled Course / Program <span className="text-rose-500">*</span>
              </label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                  <LucideBookOpen className="w-4 h-4" />
                </div>
                <select
                  value={course}
                  onChange={(e) => setCourse(e.target.value)}
                  className="w-full pl-10 pr-10 py-2.5 rounded-xl border border-slate-200 bg-white text-slate-900 text-xs sm:text-sm appearance-none focus:outline-none focus:ring-2 focus:ring-blue-600/15 focus:border-blue-600 transition-all shadow-2xs cursor-pointer font-medium"
                >
                  {STANDARD_COURSES.map((c) => (
                    <option key={c} value={c}>
                      {c === 'Other' ? '+ Custom / Other Course...' : c}
                    </option>
                  ))}
                </select>
                <div className="absolute inset-y-0 right-0 pr-3.5 flex items-center pointer-events-none text-slate-400">
                  <LucideChevronDown className="w-4 h-4" />
                </div>
              </div>

              {/* Custom Course Input */}
              {course === 'Other' && (
                <div className="pt-1.5 animate-in fade-in slide-in-from-top-1 duration-150">
                  <input
                    type="text"
                    required
                    autoFocus
                    value={customCourse}
                    onChange={(e) => setCustomCourse(e.target.value)}
                    placeholder="Type custom course title (e.g. Duolingo English Test)"
                    className="w-full px-3.5 py-2 rounded-xl border border-blue-300 bg-blue-50/20 text-slate-900 text-xs sm:text-sm focus:outline-none focus:ring-2 focus:ring-blue-600/15 focus:border-blue-600 transition-all shadow-2xs"
                  />
                </div>
              )}
            </div>

            {/* 3. Total Fee Input */}
            <div className="space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-semibold text-slate-700">
                  Total Agreed Fee (PKR) <span className="text-rose-500">*</span>
                </label>
                <span className="text-[11px] font-medium text-slate-500">
                  Remaining: <span className="font-bold text-rose-600">Rs. {parsedFeeNumber.toLocaleString()}</span>
                </span>
              </div>

              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-3 flex items-center pointer-events-none">
                  <span className="text-[11px] font-bold text-slate-500 bg-slate-100 px-2 py-0.5 rounded-md border border-slate-200">
                    Rs.
                  </span>
                </div>
                <input
                  type="number"
                  required
                  min="0"
                  step="500"
                  value={totalFee}
                  onChange={(e) => setTotalFee(e.target.value)}
                  placeholder="60000"
                  className="w-full pl-14 pr-3.5 py-2.5 rounded-xl border border-slate-200 bg-white text-slate-900 font-mono font-bold text-xs sm:text-sm focus:outline-none focus:ring-2 focus:ring-blue-600/15 focus:border-blue-600 transition-all shadow-2xs"
                />
              </div>

              {/* Presets Segment */}
              <div className="flex items-center gap-1.5 pt-0.5">
                <span className="text-[11px] text-slate-400 font-medium mr-1">Presets:</span>
                {PRESET_FEES.map((f) => (
                  <button
                    key={f}
                    type="button"
                    onClick={() => setTotalFee(f.toString())}
                    className={`px-2.5 py-0.5 rounded-md text-[10px] font-mono font-semibold transition-all border cursor-pointer ${
                      totalFee === f.toString()
                        ? 'bg-blue-50 text-blue-700 border-blue-300 shadow-2xs'
                        : 'bg-slate-50 text-slate-600 hover:bg-slate-100 border-slate-200'
                    }`}
                  >
                    Rs. {f.toLocaleString()}
                  </button>
                ))}
              </div>
            </div>

            {/* Form Actions */}
            <div className="pt-3 flex items-center justify-between gap-3 border-t border-slate-100">
              <button
                type="button"
                onClick={() => navigate('/admin/students')}
                className="px-4 py-2 rounded-xl border border-slate-200 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors cursor-pointer"
              >
                Back
              </button>

              <button
                type="submit"
                disabled={isGeneratingId}
                className="px-5 py-2.5 rounded-xl bg-gradient-to-r from-[#0d1728] via-[#111e38] to-[#162544] hover:from-[#162544] hover:to-[#0d1728] text-white font-bold text-xs shadow-md transition-all flex items-center gap-2 disabled:opacity-60 cursor-pointer"
              >
                {isGeneratingId ? (
                  <>
                    <div className="w-3.5 h-3.5 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                    <span>Generating ID...</span>
                  </>
                ) : (
                  <>
                    <span>Save Student</span>
                    <LucideArrowRight className="w-3.5 h-3.5" />
                  </>
                )}
              </button>
            </div>
          </form>
        </div>
      ) : (
        /* ===================================================================== */
        /* SCREEN 2: CLEAN OFFICIAL ADMISSION REVIEW CARD                        */
        /* Displays ONLY: Unique ID, Student Name, Course, Total Fee             */
        /* ===================================================================== */
        <div className="bg-white rounded-2xl border border-slate-200/90 shadow-lg overflow-hidden animate-in fade-in zoom-in-95 duration-200 max-w-lg mx-auto">
          {/* Official Academy Header */}
          <div className="bg-[#0d1728] text-white px-6 py-5 flex items-center justify-between border-b border-slate-800">
            <div>
              <span className="text-[10px] font-bold tracking-widest uppercase text-blue-400 block mb-0.5">
                Primes Academy • Admission Portal
              </span>
              <h2 className="text-base sm:text-lg font-bold text-white tracking-tight">
                Student Admission Review
              </h2>
            </div>
            <div className="w-10 h-10 rounded-xl bg-blue-500/20 border border-blue-400/30 flex items-center justify-center text-blue-300 shadow-inner">
              <LucideGraduationCap className="w-5 h-5 text-blue-400" />
            </div>
          </div>

          {/* Review Sheet Body */}
          <div className="p-6 sm:p-7 space-y-5">
            {/* 4 Clean Key-Value Rows */}
            <div className="bg-slate-50/70 rounded-xl border border-slate-200/90 divide-y divide-slate-200/80 overflow-hidden shadow-2xs">
              
              {/* 1. Unique Student ID */}
              <div className="p-4 flex items-center justify-between gap-4 bg-white/70">
                <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
                  Unique Student ID
                </span>
                <span className="font-mono font-black text-xl text-blue-700 bg-blue-50 px-3 py-1 rounded-lg border border-blue-200 shadow-2xs">
                  #{autoGeneratedId}
                </span>
              </div>

              {/* 2. Student Full Name */}
              <div className="p-4 flex items-center justify-between gap-4">
                <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
                  Student Name
                </span>
                <span className="font-bold text-sm sm:text-base text-slate-900 text-right">
                  {name}
                </span>
              </div>

              {/* 3. Enrolled Course */}
              <div className="p-4 flex items-center justify-between gap-4 bg-white/70">
                <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
                  Course
                </span>
                <span className="font-bold text-xs sm:text-sm text-slate-800 bg-slate-100 px-3 py-1 rounded-md border border-slate-200 text-right">
                  {finalCourse}
                </span>
              </div>

              {/* 4. Total Course Fee */}
              <div className="p-4 flex items-center justify-between gap-4">
                <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
                  Total Fee
                </span>
                <span className="font-mono font-black text-lg text-emerald-700 text-right">
                  Rs. {parsedFeeNumber.toLocaleString()}
                </span>
              </div>

            </div>

            {/* Action Buttons: Edit or Save */}
            <div className="pt-2 flex items-center justify-between gap-3">
              <button
                type="button"
                disabled={isSaving}
                onClick={() => setIsReviewing(false)}
                className="px-4 py-2.5 rounded-xl border border-slate-300 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors flex items-center gap-1.5 cursor-pointer"
              >
                <LucideArrowLeft className="w-3.5 h-3.5" />
                <span>Edit Details</span>
              </button>

              <button
                type="button"
                onClick={handleFinalSave}
                disabled={isSaving}
                className="flex-1 py-2.5 px-5 rounded-xl bg-gradient-to-r from-emerald-600 to-emerald-700 hover:from-emerald-700 hover:to-emerald-800 text-white font-bold text-xs sm:text-sm shadow-md transition-all flex items-center justify-center gap-2 disabled:opacity-60 cursor-pointer"
              >
                {isSaving ? (
                  <>
                    <div className="w-3.5 h-3.5 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                    <span>Saving...</span>
                  </>
                ) : (
                  <>
                    <LucideCheckCircle2 className="w-4 h-4" />
                    <span>Save Student</span>
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
